"""Write the data audit + EDA report as markdown, including a 'what this means for modelling' section."""
from pathlib import Path

import pandas as pd


def _md_table(rows: list[dict], cols: list[str]) -> str:
    if not rows:
        return "_none_"
    head = "| " + " | ".join(cols) + " |\n|" + "---|" * len(cols)
    body = "\n".join("| " + " | ".join(str(r.get(c, "")).replace("|", "/") for c in cols) + " |" for r in rows)
    return head + "\n" + body


def modelling_implications(audit: dict, t: dict) -> list[str]:
    out = []
    wd = t["weekday"]["rel"]
    amp = float(wd.max() - wd.min())
    if amp > 0.2:
        out.append(f"**Strong weekly pattern** (weekday spread {amp:.0%} of average). Keep lags that are multiples of 7 and a weekday feature.")
    mo = t["month"]["rel"]
    if float(mo.max() - mo.min()) > 0.15:
        out.append("**Yearly seasonality is visible**: keep month / week-of-year features.")
    ev = t["events"]
    if ev.get("available"):
        if abs(ev["uplift"]) > 0.1:
            out.append(f"**Events matter** (sales {ev['uplift']:+.0%} on event days): keep the event flag; the Critic should treat events as known risk.")
        else:
            out.append(f"Events change average sales little ({ev['uplift']:+.0%}); a low Critic weight for events is expected.")
    if audit["demand"]["mass_zero_days"]:
        out.append("**Store-closure days exist** (" + ", ".join(audit["demand"]["mass_zero_days"][:4]) + "): they must be known in advance (event flag), otherwise they look like demand collapses.")
    cl = audit["demand"]["classes"]
    n = sum(cl.values()) or 1
    hard = (cl.get("intermittent", 0) + cl.get("lumpy", 0)) / n
    out.append(f"**{hard:.0%} of series are intermittent or lumpy.** " + ("Use a count (Poisson) loss and judge with WAPE; classical methods will struggle on these." if hard > 0.2 else "Most series are smooth or erratic, so standard forecasting applies."))
    pr = t["price"]
    if pr.get("available"):
        if pr["median_slope"] < -0.05 and pr["share_negative"] > 0.6:
            out.append(f"**Price moves demand** (median slope {pr['median_slope']:.2f}, negative for {pr['share_negative']:.0%} of series): keep price features.")
        else:
            out.append(f"Price has a weak, inconsistent effect (median slope {pr['median_slope']:.2f}); price features may add little.")
    we = t["weather"]
    if we.get("available"):
        if we["share_abs_corr_gt_0_1"] > 0.25:
            out.append(f"**Weather matters for {we['share_abs_corr_gt_0_1']:.0%} of series**: keep weather features and the Critic's weather signal.")
        else:
            out.append(f"**Weather has a weak link to sales** (only {we['share_abs_corr_gt_0_1']:.0%} of series have |corr| > 0.1): expect little gain from weather.")
    else:
        out.append("No usable weather in this table: weather features and the Critic's weather signal are inactive.")
    ab = t["abc_summary"].set_index("abc")
    if "A" in ab.index:
        out.append(f"**Volume is concentrated**: {int(ab.loc['A', 'series'])} of {int(ab['series'].sum())} series carry {ab.loc['A', 'volume_share']:.0%} of the volume; consider per-class service levels.")
    a7 = t["acf"].set_index("lag")["acf"]
    if 7 in a7.index and a7[7] > 0.5:
        out.append(f"Total demand is strongly autocorrelated at lag 7 ({a7[7]:.2f}): a 7-day-ahead forecast can lean on last week.")
    return out


def write_report(path, audit: dict, t: dict, cleaning_log: list[dict] | None, weather_audit: dict | None, figures: dict[str, str]) -> str:
    o, q = audit["overview"], audit["quality"]
    lines = [f"# Data audit and EDA - {audit['name']}", "",
             "_Generated by `demand-agents eda`. Numbers describe the data actually used; rerun after any change to the data._", "",
             "## 1. Overview", "",
             f"- Period: **{o['start']} to {o['end']}** ({o['periods']} {'days' if audit['frequency'] == 'D' else 'weeks'})",
             f"- Series: **{o['series']}**" + (f" ({o['stores']} stores x {o['items']} items)" if o.get('stores') and o.get('items') else ""),
             f"- Rows: **{o['rows']:,}**; zero-sales share **{audit['demand']['zero_share']:.1%}**; mean sales {audit['demand']['mean_sales']:.2f}",
             f"- Demand types: {audit['demand']['classes']}", "", "## 2. Cleaning applied", ""]
    lines.append(_md_table(cleaning_log or [], ["step", "rows_affected", "note"]) if cleaning_log else "_No cleaning log found. Run `demand-agents build` first._")
    lines += ["", "Deliberately **not** removed: demand spikes and zero-sales days (they are the shocks under study).", "",
              "## 3. Issues found", "", _md_table(audit["issues"], ["severity", "check", "detail", "action"]), ""]
    lines += ["## 4. Integration", ""]
    if weather_audit:
        lines += [f"- Weather: {', '.join(weather_audit['states'])}, {weather_audit['start']} to {weather_audit['end']}, "
                  f"{weather_audit['missing_share']:.1%} of station-days missing after cleaning",
                  f"- Share of sales dates covered by weather: {weather_audit.get('panel_date_coverage', float('nan')):.1%}",
                  f"- Share of modelling-table rows with a temperature: {weather_audit.get('panel_rows_with_temperature', float('nan')):.1%}"]
        lines += [f"- Issue: {i['check']} - {i['detail']}" for i in weather_audit["issues"]]
    else:
        lines.append("- No external weather merged into this table.")
    lines += ["- M5 and Walmart are **not** merged with each other (different stores, period, measure and frequency); each is modelled separately.", "",
              "## 5. Exploratory findings", ""]
    captions = {"total_demand": "Total demand", "seasonality": "Weekday and month profiles", "events": "Event effect", "intermittency": "Demand types",
                "price_response": "Price response", "weather_response": "Weather response", "volume_concentration": "Volume concentration",
                "zero_share": "Zero sales per series", "autocorrelation": "Autocorrelation"}
    for k, f in figures.items():
        lines += [f"![{captions.get(k, k)}](figures/{Path(f).name})", ""]
    lines += ["## 6. What this means for modelling", ""] + [f"- {s}" for s in modelling_implications(audit, t)] + [""]
    text = "\n".join(lines)
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text(text)
    return text
